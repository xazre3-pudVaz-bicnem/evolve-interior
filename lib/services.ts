/**
 * 事業内容（工事種別）のデータ。
 *
 * 各詳細ページは「文章を少し変えただけの量産ページ」にしないため、
 * - detail（説明の段落数）
 * - extra（工事ごとに種類の異なる固有ブロック：一覧 / 比較表 / 補足）
 * - steps（工程の粒度と数）
 * - faqs
 * をすべて工事ごとに個別に作成している。
 *
 * ※ 実績年数・施工件数・資格・保証・「最短」「無料」などの
 *    未提供情報は一切記載しない。対応可否が現場条件に依存する項目は
 *    断定せず「ご相談ください」に留める。
 */

export type ServiceExtra =
  | {
      kind: 'terms'
      title: string
      lead?: string
      items: { term: string; desc: string }[]
    }
  | {
      kind: 'compare'
      title: string
      lead?: string
      head: [string, string]
      rows: { label: string; a: string; b: string }[]
    }
  | {
      kind: 'flowNote'
      title: string
      lead?: string
      body: string[]
    }

export type Service = {
  slug: string
  name: string
  nameEn: string
  /** 一覧カード用の1行説明 */
  short: string
  /** 詳細ページ冒頭のリード文 */
  lead: string
  /** 一般の方向けの、専門用語を避けた説明 */
  plain: string
  /** もう少し踏み込んだ説明（段落） */
  detail: string[]
  /** 主な施工場所 */
  places: string[]
  /** 依頼対象 */
  clients: string[]
  /** 施工の流れ */
  steps: { title: string; body: string }[]
  /** 工事ごとに構造の異なる固有ブロック */
  extra: ServiceExtra
  faqs: { q: string; a: string }[]
  /** 期待する画像ファイル名（public/images/ 配下・未設置なら仮枠を表示） */
  image: string
  /** 写真に実際に写っているものを説明する alt。見出しから機械的に生成しないこと */
  imageAlt: string
  metaTitle: string
  metaDescription: string
  keywords: string[]
}

